# 2文字のカタカナでも英語の音から当てられるもの（検査は3文字以上なので素通りする）。
# ゴミ・カビは和語のカタカナ表記で音の手がかりにならないので残す。全語で一括置換
GLOBAL = {
    "歯車、ギア":                     "歯車",
    "錠剤、ピル":                     "錠剤",
    "記録する、ログに残す":           "記録する",
    "ピンで留める、固定する":         "留める、固定する",
    "ポンと破裂する、弾ける":         "破裂する、弾ける",
    "パッとひっくり返す、素早く動かす": "ぱっとひっくり返す、素早く動かす",
}


def main():
    data = json.load(open(PATH, encoding="utf-8"))
    by_id = {w["id"]: w for w in data}
    for i, label in CHOICE_LABELS.items():
        print(f"#{i:4d} {by_id[i]['word']:<12s} choiceLabel {by_id[i].get('choiceLabel')!r} → {label!r}")
        by_id[i]["choiceLabel"] = label
    for i, old, new in DISTRACTORS:
        ds = by_id[i]["distractors"]
        if old not in ds:
            sys.exit(f"#{i} {by_id[i]['word']}: 誤答 {old!r} が見つからない: {ds}")
        ds[ds.index(old)] = new
        print(f"#{i:4d} {by_id[i]['word']:<12s} 誤答 {old} → {new}")
    for w in data:
        correct = w.get("choiceLabel") or w["meanings"][0]["meaning"]
        if correct in GLOBAL:
            print(f"#{w['id']:4d} {w['word']:<12s} choiceLabel → {GLOBAL[correct]!r}")
            w["choiceLabel"] = GLOBAL[correct]
        for j, d in enumerate(w["distractors"]):
            if d in GLOBAL:
                w["distractors"][j] = GLOBAL[d]
    if "--apply" in sys.argv:
        json.dump(data, open(PATH, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
        print("→ 書き込みました")


if __name__ == "__main__":
    main()
